// Copies the display fields the workspace screen needs from the real registry (src/data/projects.js),
// verbatim, so nothing on the CRT is retyped by hand. Re-run to refresh: node tools/snapshot-projects.mjs
import { writeFileSync } from 'node:fs';
import { PROJECTS } from '../../src/data/projects.js';

const SLUGS = ['zarvin-one', 'proof-first'];
const FIELDS = ['slug', 'n', 'title', 'titleEm', 'kind', 'year', 'desc', 'tags', 'role', 'status', 'statusBadge', 'outcome', 'stack', 'demo', 'site', 'publicStatus'];
const out = SLUGS.map((slug) => {
  const p = PROJECTS.find((x) => x.slug === slug);
  if (!p) throw new Error(`registry has no project ${slug}`);
  return Object.fromEntries(FIELDS.filter((f) => p[f] != null).map((f) => [f, p[f]]));
});
writeFileSync(new URL('../src/project-data.js', import.meta.url),
  `// GENERATED by tools/snapshot-projects.mjs from src/data/projects.js: do not edit by hand.\nexport const SCREEN_PROJECTS = ${JSON.stringify(out, null, 2)};\n`);
console.log('wrote', out.map((p) => p.slug).join(', '));
